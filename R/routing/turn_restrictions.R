# Polaris Routing Engine: Dual Graph Transformation & Turn Restriction Modeling
# Line-graph expansion handling turn prohibitions and maneuver delay penalties

#' Construct Edge-Expanded Dual Graph
#'
#' Transforms an intersection-based graph into an edge-based line graph
#' where vertices represent road segments and transitions encode legal maneuvers.
#'
#' @param graph Base polaris_graph object
#' @param restrictions List of polaris_turn_restriction objects
#' @param default_left_turn_penalty Seconds added to left turn maneuvers (default 8.0s)
#' @param default_u_turn_penalty Seconds added to U-turn maneuvers (default 20.0s)
#' @return A new polaris_graph instance representing the dual network
#' @export
build_dual_graph <- function(graph, restrictions = list(),
                             default_left_turn_penalty = 8.0,
                             default_u_turn_penalty = 20.0) {
  dual_g <- polaris_graph()

  # Hash map of restricted transitions: 'from_edge|via_node|to_edge' -> penalty/prohibition
  restr_map <- new.env(hash = TRUE, parent = emptyenv())
  for (r in restrictions) {
    key <- sprintf("%s|%s|%s", r$from_edge, r$via_node, r$to_edge)
    restr_map[[key]] <- r
  }

  # Step 1: Each base edge becomes a dual node
  for (e_id in graph$edge_ids) {
    edge_obj <- graph$get_edge(e_id)
    # Representative coordinate is midpoint of edge
    src_coord <- graph$node_coords[[edge_obj$source]]
    tgt_coord <- graph$node_coords[[edge_obj$target]]
    mid_lat <- (src_coord$lat + tgt_coord$lat) / 2.0
    mid_lon <- (src_coord$lon + tgt_coord$lon) / 2.0

    dual_g$add_node(
      id = e_id,
      lat = mid_lat,
      lon = mid_lon,
      tags = list(
        base_source = edge_obj$source,
        base_target = edge_obj$target,
        base_length = edge_obj$distance,
        base_time = edge_obj$travel_time
      )
    )
  }

  # Step 2: Transitions between consecutive edges
  for (e1_id in graph$edge_ids) {
    e1 <- graph$get_edge(e1_id)
    v_via <- e1$target
    out_edges <- graph$forward_adj[[v_via]]

    for (e2 in out_edges) {
      e2_id <- e2$id
      restr_key <- sprintf("%s|%s|%s", e1_id, v_via, e2_id)
      restr <- restr_map[[restr_key]]

      # Check if prohibited
      if (!is.null(restr)) {
        if (restr$restriction_type %in% c("no_left_turn", "no_right_turn", "no_u_turn", "prohibited")) {
          next # Prohibited maneuver: do not create dual transition edge
        }
      }

      # Check for U-turn (e2 returns to e1$source)
      is_uturn <- (e2$target == e1$source)
      if (is_uturn && !is.null(restr) && restr$restriction_type == "no_u_turn") {
        next
      }

      # Compute maneuver penalty
      penalty <- 0.0
      if (!is.null(restr) && restr$restriction_type == "penalty") {
        penalty <- restr$penalty_seconds
      } else if (is_uturn) {
        penalty <- default_u_turn_penalty
      } else {
        # Estimate turning angle from bearings
        c_prev <- graph$node_coords[[e1$source]]
        c_via  <- graph$node_coords[[v_via]]
        c_next <- graph$node_coords[[e2$target]]

        b_in <- initial_bearing(c_prev$lat, c_prev$lon, c_via$lat, c_via$lon)
        b_out <- initial_bearing(c_via$lat, c_via$lon, c_next$lat, c_next$lon)
        turn_angle <- ((b_out - b_in + 180.0) %% 360.0) - 180.0

        if (turn_angle < -45.0) {
          # Left turn
          penalty <- default_left_turn_penalty
        }
      }

      trans_id <- sprintf("trans_%s_%s", e1_id, e2_id)
      dual_g$add_edge(
        id = trans_id,
        source = e1_id,
        target = e2_id,
        distance = e2$distance,
        travel_time = e2$travel_time + penalty,
        speed_limit = e2$speed_limit,
        oneway = TRUE,
        highway_type = e2$highway_type
      )
    }
  }

  dual_g$build_csr()
  dual_g
}

#' Route with Turn Restrictions on Dual Graph
#'
#' @param dual_graph polaris_graph generated by build_dual_graph()
#' @param base_graph Underlying physical polaris_graph
#' @param source_id Origin intersection node ID in base graph
#' @param target_id Destination intersection node ID in base graph
#' @param metric 'distance' or 'time'
#' @return polaris_route_result object
#' @export
polaris_turn_constrained_route <- function(dual_graph, base_graph,
                                           source_id, target_id, metric = "time") {
  s_str <- as.character(source_id)
  t_str <- as.character(target_id)

  # Find entry edges in dual graph (edges departing source in base graph)
  entry_edges <- vapply(base_graph$forward_adj[[s_str]], function(e) e$id, character(1))
  # Find exit edges in dual graph (edges entering target in base graph)
  exit_edges <- vapply(base_graph$backward_adj[[t_str]], function(e) e$id, character(1))

  if (length(entry_edges) == 0L || length(exit_edges) == 0L) {
    return(polaris_route_result(
      nodes = character(0),
      edges = character(0),
      total_distance = Inf,
      total_time = Inf,
      algorithm = "turn_constrained_dual",
      status = "NO_PATH_FOUND"
    ))
  }

  best_route <- NULL
  best_cost <- Inf

  for (ent in entry_edges) {
    for (ext in exit_edges) {
      res <- polaris_dijkstra(dual_graph, source_id = ent, target_id = ext, metric = metric)
      if (res$status == "OK") {
        c_val <- if (metric == "time") res$total_time else res$total_distance
        if (c_val < best_cost) {
          best_cost <- c_val
          best_route <- res
        }
      }
    }
  }

  if (is.null(best_route)) {
    return(polaris_route_result(
      nodes = character(0),
      edges = character(0),
      total_distance = Inf,
      total_time = Inf,
      algorithm = "turn_constrained_dual",
      status = "NO_PATH_FOUND"
    ))
  }

  # In dual graph, nodes along the path are the edge IDs of the base graph
  base_edge_ids <- best_route$nodes

  # Reconstruct base vertices
  base_nodes <- character(length(base_edge_ids) + 1L)
  base_nodes[1L] <- s_str
  for (i in seq_along(base_edge_ids)) {
    e_obj <- base_graph$get_edge(base_edge_ids[i])
    base_nodes[i + 1L] <- e_obj$target
  }

  tot_dist <- 0.0
  tot_time <- 0.0
  geom_list <- list()

  for (e_id in base_edge_ids) {
    e_obj <- base_graph$get_edge(e_id)
    tot_dist <- tot_dist + e_obj$distance
    tot_time <- tot_time + e_obj$travel_time
  }
  for (nd in base_nodes) {
    geom_list[[length(geom_list) + 1L]] <- base_graph$node_coords[[nd]]
  }

  polaris_route_result(
    nodes = base_nodes,
    edges = base_edge_ids,
    total_distance = tot_dist,
    total_time = best_route$total_time, # includes turn maneuver penalties
    geometry = geom_list,
    algorithm = "turn_constrained_dual",
    status = "OK"
  )
}
